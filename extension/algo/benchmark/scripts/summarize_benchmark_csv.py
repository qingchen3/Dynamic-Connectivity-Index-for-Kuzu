#!/usr/bin/env python3

import argparse
import csv
import statistics
from collections import defaultdict
from pathlib import Path


METRICS = [
    "insert_avg_us",
    "delete_avg_us",
]


def parse_float(value):
    if value is None:
        return None
    value = value.strip()
    if value == "":
        return None
    try:
        return float(value)
    except ValueError:
        return None


def summarize(values):
    values = [v for v in values if v is not None]
    if not values:
        return None

    result = {
        "runs": len(values),
        "mean": statistics.mean(values),
        "median": statistics.median(values),
        "min": min(values),
        "max": max(values),
        "stddev": statistics.stdev(values) if len(values) > 1 else 0.0,
    }
    return result


def main():
    parser = argparse.ArgumentParser(
        description="Summarize dynamic connectivity benchmark summary.csv files."
    )
    parser.add_argument("summary_csv", help="Path to summary.csv generated by run_benchmark_repeats.sh")
    parser.add_argument(
        "--out",
        help="Optional path to write aggregate summary CSV. Default: aggregate_summary.csv next to input.",
        default=None,
    )
    args = parser.parse_args()

    summary_path = Path(args.summary_csv)
    if not summary_path.exists():
        raise FileNotFoundError(f"Summary CSV not found: {summary_path}")

    grouped = defaultdict(lambda: defaultdict(list))

    with summary_path.open(newline="") as f:
        reader = csv.DictReader(f)

        required_columns = {"method", "insert_avg_us", "delete_avg_us"}
        missing = required_columns - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"Missing required columns: {sorted(missing)}")

        for row in reader:
            method = row["method"]
            exit_code = row.get("exit_code", "0").strip()
            validation_errors = row.get("validation_errors", "0").strip()

            # Skip failed runs.
            if exit_code not in ("", "0"):
                continue

            # Skip runs with validation errors.
            if validation_errors not in ("", "0"):
                continue

            for metric in METRICS:
                grouped[method][metric].append(parse_float(row.get(metric)))

    output_rows = []

    print("========== Benchmark Summary ==========")
    print(f"Input: {summary_path}")
    print()
    print(
        f"{'method':<8} {'metric':<16} {'runs':>5} "
        f"{'mean':>12} {'median':>12} {'stddev':>12} {'min':>12} {'max':>12}"
    )

    for method in sorted(grouped.keys()):
        for metric in METRICS:
            stats = summarize(grouped[method][metric])
            if stats is None:
                continue

            output_rows.append({
                "method": method,
                "metric": metric,
                **stats,
            })

            print(
                f"{method:<8} {metric:<16} {stats['runs']:>5} "
                f"{stats['mean']:>12.6f} {stats['median']:>12.6f} "
                f"{stats['stddev']:>12.6f} {stats['min']:>12.6f} {stats['max']:>12.6f}"
            )

    print()

    # Print simple STree/DTree speedups if both exist.
    means = {
        (row["method"], row["metric"]): row["mean"]
        for row in output_rows
    }

    for metric in METRICS:
        stree = means.get(("stree", metric))
        dtree = means.get(("dtree", metric))
        if stree is not None and dtree is not None:
            if stree < dtree:
                print(f"{metric}: STree is {dtree / stree:.3f}x faster than DTree")
            elif dtree < stree:
                print(f"{metric}: DTree is {stree / dtree:.3f}x faster than STree")
            else:
                print(f"{metric}: STree and DTree are tied")

    out_path = Path(args.out) if args.out else summary_path.parent / "aggregate_summary.csv"

    with out_path.open("w", newline="") as f:
        fieldnames = ["method", "metric", "runs", "mean", "median", "stddev", "min", "max"]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in output_rows:
            writer.writerow(row)

    print()
    print(f"Wrote aggregate summary: {out_path}")


if __name__ == "__main__":
    main()